"use client";
import { useState } from "react";
import { UserMedicine, FamilyMember } from "@/lib/api";

interface ExportData {
  userName: string;
  userEmail: string;
  medicines: UserMedicine[];
  familyMembers?: FamilyMember[];
}

export function MedicinePDFExport({ data }: { data: ExportData }) {
  const [exporting, setExporting] = useState(false);

  const generatePDF = async () => {
    setExporting(true);
    try {
      const { jsPDF } = await import("jspdf");
      const doc = new jsPDF();
      const pageWidth = doc.internal.pageSize.getWidth();
      const margin = 20;
      let y = 20;

      // Header
      doc.setFillColor(14, 165, 233);
      doc.rect(0, 0, pageWidth, 40, "F");

      doc.setTextColor(255, 255, 255);
      doc.setFontSize(24);
      doc.setFont("helvetica", "bold");
      doc.text("PillWise", margin, 18);

      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      doc.text("Medicine List - Be Wise Before You Take", margin, 28);

      doc.setFontSize(8);
      doc.text(`Generated: ${new Date().toLocaleDateString()}`, pageWidth - margin, 18, { align: "right" });
      doc.text(`www.pillwise.pk`, pageWidth - margin, 24, { align: "right" });

      y = 55;

      // Patient Info
      doc.setTextColor(0, 0, 0);
      doc.setFontSize(14);
      doc.setFont("helvetica", "bold");
      doc.text("Patient Information", margin, y);
      y += 10;

      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      doc.text(`Name: ${data.userName}`, margin, y);
      y += 6;
      doc.text(`Email: ${data.userEmail}`, margin, y);
      y += 6;
      doc.text(`Export Date: ${new Date().toLocaleDateString()}`, margin, y);
      y += 12;

      // Medicines Table
      doc.setFontSize(14);
      doc.setFont("helvetica", "bold");
      doc.text("Current Medicines", margin, y);
      y += 10;

      if (data.medicines.length === 0) {
        doc.setFontSize(10);
        doc.setFont("helvetica", "normal");
        doc.text("No medicines added yet.", margin, y);
        y += 10;
      } else {
        // Table header
        doc.setFillColor(14, 165, 233);
        doc.rect(margin, y - 5, pageWidth - 2 * margin, 8, "F");
        doc.setTextColor(255, 255, 255);
        doc.setFontSize(9);
        doc.setFont("helvetica", "bold");
        doc.text("#", margin + 2, y);
        doc.text("Medicine", margin + 12, y);
        doc.text("Dosage", margin + 80, y);
        doc.text("Timing", margin + 120, y);
        y += 8;

        doc.setTextColor(0, 0, 0);
        doc.setFont("helvetica", "normal");
        doc.setFontSize(10);

        data.medicines.forEach((med, index) => {
          if (y > 270) {
            doc.addPage();
            y = 20;
          }

          if (index % 2 === 0) {
            doc.setFillColor(240, 245, 255);
            doc.rect(margin, y - 4, pageWidth - 2 * margin, 8, "F");
          }

          doc.text(`${index + 1}`, margin + 2, y);
          doc.text(med.medicineName.substring(0, 30), margin + 12, y);
          doc.text(med.dosage || "-", margin + 80, y);
          doc.text(med.timing || "-", margin + 120, y);
          y += 8;
        });

        y += 5;
        doc.setDrawColor(200, 200, 200);
        doc.line(margin, y, pageWidth - margin, y);
        y += 10;
      }

      // Family Members
      if (data.familyMembers && data.familyMembers.length > 0) {
        if (y > 240) {
          doc.addPage();
          y = 20;
        }

        doc.setFontSize(14);
        doc.setFont("helvetica", "bold");
        doc.setTextColor(0, 0, 0);
        doc.text("Family Members", margin, y);
        y += 10;

        doc.setFontSize(10);
        doc.setFont("helvetica", "normal");
        data.familyMembers.forEach((member) => {
          doc.text(`• ${member.name} (${member.relation || "N/A"})${member.age ? ` - ${member.age} years` : ""}`, margin, y);
          y += 6;
        });
        y += 10;
      }

      // Warnings
      if (y > 220) {
        doc.addPage();
        y = 20;
      }

      doc.setFillColor(255, 243, 205);
      doc.rect(margin, y, pageWidth - 2 * margin, 30, "F");
      doc.setDrawColor(255, 193, 7);
      doc.rect(margin, y, pageWidth - 2 * margin, 30);

      doc.setTextColor(133, 100, 4);
      doc.setFontSize(11);
      doc.setFont("helvetica", "bold");
      doc.text("⚠️ Important Disclaimer", margin + 5, y + 10);

      doc.setFontSize(8);
      doc.setFont("helvetica", "normal");
      doc.text("This document is generated by PillWise for informational purposes only.", margin + 5, y + 18);
      doc.text("Always consult your doctor or pharmacist before making any changes to your medications.", margin + 5, y + 24);

      // Footer
      const pageCount = doc.getNumberOfPages();
      for (let i = 1; i <= pageCount; i++) {
        doc.setPage(i);
        doc.setFontSize(8);
        doc.setTextColor(150, 150, 150);
        doc.text(
          `PillWise - Medicine Interaction Checker | Page ${i} of ${pageCount}`,
          pageWidth / 2,
          doc.internal.pageSize.getHeight() - 10,
          { align: "center" }
        );
      }

      doc.save(`PillWise_Medicines_${data.userName.replace(/\s+/g, "_")}_${new Date().toISOString().split("T")[0]}.pdf`);
    } catch (err) {
      console.error("PDF export failed:", err);
      alert("Failed to generate PDF. Please try again.");
    } finally {
      setExporting(false);
    }
  };

  return (
    <button
      onClick={generatePDF}
      disabled={exporting}
      className="btn-primary px-6 py-3 text-white font-medium rounded-xl flex items-center gap-2 disabled:opacity-50"
    >
      {exporting ? (
        <>
          <span className="animate-spin-slow inline-block w-4 h-4 border-2 border-white/30 border-t-white rounded-full" />
          Generating...
        </>
      ) : (
        <>
          📄 Export PDF
        </>
      )}
    </button>
  );
}
